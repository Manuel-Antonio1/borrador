    private void calcularPromedioYObservacion(Alumno a) {
        double promedio = (a.getEc1() + a.getEc2() + a.getEc3() + a.getPromedio()) / 4;
    a.setFinali(promedio);

    if (promedio > 13) {
        a.setObser("Aprobado");
    } else if (promedio >= 12) {
        a.setObser("Desaprobado");
    } else {
        a.setObser("Deficiente");
    }
    }


