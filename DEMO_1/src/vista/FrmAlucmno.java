    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        Alumno a = new Alumno();

        a.setCodigo(txtCodigo.getText());
        a.setNombre(txtNombre.getText());
        a.setApeliido(txtApellido.getText());
        a.setCurso(cbCurso.getSelectedItem().toString() );
        a.setEc1(Double.parseDouble(txtNota1.getText()));
        a.setEc2(Double.parseDouble(txtNota2.getText()));
        a.setEc3(Double.parseDouble(txtNota3.getText()));
        a.setPromedio(Double.parseDouble(txtNotaF.getText()));
       
       
      
        calcularPromedioYObservacion(a);

        txtPromedio.setText(String.valueOf(a.getFinali()));
        txtObser.setText(String.valueOf(a.getObser()));

        dao.agregar(a);

        JOptionPane.showMessageDialog(null, "Registro agregado correctamente");
        
        
       


    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

       int fila = tablaAlumno.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione un registro");
            return;
        }
        int opcion = JOptionPane.showConfirmDialog(null, "¿Desea eliminar un Alucmno ?", "Confirmar",
                JOptionPane.YES_NO_OPTION);
        if (opcion == JOptionPane.YES_OPTION) {
            String codigo = tablaAlumno.getValueAt(fila, 0).toString();

            dao.eliminar(codigo);  
            list();
             btnListarActionPerformed(null);
            

           
        }

        

        
    }//GEN-LAST:event_btnEliminarActionPerformed

